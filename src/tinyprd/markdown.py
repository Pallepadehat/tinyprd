"""Gør modellens output til en rigtig `prd.md`, man kan bruge med det samme.

Modellen skriver i et enkelt format med små bogstaver:

    ## intent
    dashboard sharing
    ## problem
    analysts have no simple way to ...

`to_markdown` laver det om til et pænt Markdown-dokument med titel, en lille
faktaboks, store forbogstaver og punktlister:

    # PRD: Dashboard sharing

    > **Idea:** something that lets analysts share dashboards with coworkers.

    | | |
    |---|---|
    | **Status** | Draft |
    | **Appetite** | Three weeks, then review share completion. |
    ...

    ## Problem
    Analysts have no simple way to ...

Funktionen virker også på rodet output: ukendte sektioner beholdes, og
tomme sektioner springes over.
"""

from __future__ import annotations

from datetime import date

from .data.prd import LIST_SECTIONS, SECTION_ORDER, parse_sections

# Sektionerne i dokumentet og deres overskrift. "intent" bliver til titlen, og
# "appetite" står i faktaboksen, så de er ikke med her.
SECTION_TITLES = {
    "problem": "Problem",
    "users": "Users",
    "outcome": "Outcome",
    "success metrics": "Success metrics",
    "scope": "Scope",
    "non-goals": "Non-goals",
    "open questions": "Open questions",
}


def _capitalize(text: str) -> str:
    text = text.strip()
    return text[:1].upper() + text[1:]


def _sentence(text: str) -> str:
    """Stort forbogstav og punktum til sidst."""
    text = _capitalize(text)
    return text if not text or text[-1] in ".?!" else text + "."


def _users(lines: list[str]) -> list[str]:
    """'primary: developers. secondary: reviewers.' → '- **Primary:** developers' osv."""
    parts = [part.strip() for line in lines for part in line.split(".") if part.strip()]
    bullets = []
    for part in parts:
        role, sep, who = part.partition(":")
        bullets.append(f"- **{_capitalize(role)}:** {who.strip()}" if sep else f"- {_capitalize(part)}")
    return bullets


def to_markdown(text: str, idea: str | None = None, generated_by: str | None = None) -> str:
    """Lav modellens PRD-tekst om til et Markdown-dokument."""
    sections = parse_sections(text)
    intent = " ".join(sections.get("intent", [])).strip(" .")
    out = [f"# PRD: {_capitalize(intent) or 'Untitled'}", ""]

    if idea:
        out += [f"> **Idea:** {' '.join(idea.split())}", ""]

    facts = [("Status", "Draft"), ("Date", date.today().isoformat())]
    appetite = " ".join(sections.get("appetite", []))
    if appetite:
        facts.append(("Appetite", _sentence(appetite)))
    if generated_by:
        facts.append(("Generated by", generated_by))
    out += ["| | |", "|---|---|"] + [f"| **{key}** | {value} |" for key, value in facts] + [""]

    known = set(SECTION_ORDER)
    extra = [name for name in sections if name not in known]  # rodet output kan have ukendte overskrifter
    for name in [*SECTION_TITLES, *extra]:
        lines = [line for line in sections.get(name, []) if line]
        if not lines:
            continue
        out += [f"## {SECTION_TITLES.get(name, _capitalize(name))}", ""]
        if name == "users":
            out += _users(lines)
        elif name in LIST_SECTIONS:
            out += [f"- {_capitalize(line)}" for line in lines]
        else:
            out.append(" ".join(_sentence(line) for line in lines))
        out.append("")

    return "\n".join(out).rstrip() + "\n"
